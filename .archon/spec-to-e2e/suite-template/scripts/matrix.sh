#!/usr/bin/env bash
# Prints the traceability matrix (Markdown) from the tags in features/ and the ticket
# state files in state/. Run from the suite directory:
#
#   bash scripts/matrix.sh > TRACEABILITY.md
#
# Built from the files only, never by a model, so it can be regenerated at any time and
# its rows can be pushed to Confluence as they are.
set -eu

tmp=${TMPDIR:-/tmp}/matrix-states.$$
trap 'rm -f "$tmp"' EXIT
: > "$tmp"
for s in state/*.json; do
  [ -f "$s" ] || continue
  jq -r '[.ticket, .status, (.reason // "")] | @tsv' "$s" >> "$tmp"
done

echo "# Traceability"
echo
echo "Generated by \`scripts/matrix.sh\` from the tags in \`features/\` and the files in \`state/\`. Do not edit by hand."
echo
echo "## Tickets"
echo
echo "| Ticket | Status | Reason |"
echo "|---|---|---|"
LC_ALL=C sort "$tmp" | awk -F'\t' '{printf "| %s | %s | %s |\n", $1, $2, $3}'
echo
echo "## Scenarios"
echo
echo "Status \`active\` means the scenario runs in the suite. Any other status is a tag that keeps it out: \`app-mismatch\` (the app does something else than the spec), \`unreachable\`, \`needs-test-hook\`, \`unexplored\`, \`flagged\` (its ticket is not done)."
echo
echo "| Ticket | Origin | Scenario | Status | Feature |"
echo "|---|---|---|---|---|"
find features -name '*.feature' 2>/dev/null | LC_ALL=C sort | while IFS= read -r f; do
  awk -v F="$f" '
    function trim(s) { sub(/^[ \t]+/, "", s); sub(/[ \t\r]+$/, "", s); return s }
    function info(tags,   n, i, a) {
      n = split(tags, a, /[ \t]+/)
      for (i = 1; i <= n; i++) {
        if (a[i] ~ /^@[A-Z][A-Z0-9]+-[0-9]+$/ && ticket == "") ticket = substr(a[i], 2)
        if (a[i] ~ /^@origin-/) origin = substr(a[i], 9)
        if (a[i] == "@emergent") emergent = 1
        if (a[i] ~ /^@(app-mismatch|unreachable|needs-test-hook|unexplored|flagged)$/) status = substr(a[i], 2)
      }
    }
    { l = trim($0) }
    l ~ /^Feature:/ { ftags = prev }
    l ~ /^Scenario( Outline)?:/ {
      name = l; sub(/^Scenario( Outline)?:[ \t]*/, "", name)
      ticket = ""; origin = ""; emergent = 0; status = ""
      info(prev); info(ftags)
      if (status == "") status = "active"
      if (emergent) { if (origin != "") ticket = origin; origin = "emergent" } else origin = "spec"
      gsub(/\|/, "\\|", name)
      printf "| %s | %s | %s | %s | %s:%d |\n", ticket, origin, name, status, F, NR
    }
    { prev = l }
  ' "$f"
done
